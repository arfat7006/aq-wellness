-- Run this SQL in Supabase SQL Editor.
create table if not exists public.appointment_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  phone text not null,
  service text not null,
  preferred_date date not null,
  preferred_time text not null,
  age integer,
  reason text,
  safety_info text,
  status text not null default 'Pending'
);

alter table public.appointment_requests enable row level security;

-- Public website may submit a new request only.
drop policy if exists "Anyone can submit appointment requests" on public.appointment_requests;
create policy "Anyone can submit appointment requests"
on public.appointment_requests for insert
to anon, authenticated
with check (true);

-- Only authenticated admins can view appointment requests.
drop policy if exists "Authenticated admins can view requests" on public.appointment_requests;
create policy "Authenticated admins can view requests"
on public.appointment_requests for select
to authenticated
using (auth.uid() is not null);

